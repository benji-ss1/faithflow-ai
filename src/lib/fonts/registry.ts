// Slide font registry — the single source of truth for every font the operator
// can pick (Fonts Phase 1, 2026-09-17). Pure: no DOM, no server imports.
//
// Rules (never regress):
//  - Stored values are NEVER rewritten. resolveFont() only looks things up; an
//    unknown stored value stays exactly as it was (pickers show it as
//    "(current) <value>", renderers pass it through with a generic fallback).
//  - fontStack() is RENDER-TIME only. It must not be used to mutate stored data,
//    the wire payload, or slideOutputIdentity (content identity must stay stable
//    or the fade-pulse returns — CLAUDE.md rule 7, 2026-08-19).
//  - Bundled faces live in public/fonts/<id>/ and are declared in
//    src/app/slide-fonts.css (generated by scripts/fonts/build-slide-fonts.py).

export type FontCategory = "sans" | "serif" | "display" | "mono" | "system";
export type GenericFamily = "sans-serif" | "serif" | "monospace";

export type FontEntry = {
  /** Stable id (also the public/fonts/<id> folder for bundled fonts). */
  id: string;
  /** CSS family name, exactly as stored in themes/slides today. */
  family: string;
  label: string;
  category: FontCategory;
  /** Real weights this face has (bundled) or reliably renders (system). */
  weights: number[];
  italic: boolean;
  generic: GenericFamily;
  /** Extra CSS families appended before the generic (e.g. Helvetica → Arial). */
  fallbacks?: string[];
  /** Other stored spellings that mean this font (compared case-insensitively). */
  aliases?: string[];
  /** Glyph coverage checked with fontTools on the bundled files (system: unverified = false). */
  supports: { yoruba: boolean; igbo: boolean };
  /** true = bundled woff2 in public/fonts/<id>; false = relies on the OS. */
  bundled: boolean;
  /** Kept selectable for existing content; not a recommended pick. */
  legacy?: boolean;
};

const range = (lo: number, hi: number) => {
  const out: number[] = [];
  for (let w = lo; w <= hi; w += 100) out.push(w);
  return out;
};

