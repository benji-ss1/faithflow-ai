/** Kill switch: NEXT_PUBLIC_SLIDE_FONTS_V1="0" restores raw pass-through. Default ON. */
export function slideFontsV1Enabled(): boolean {
  try {
    return process.env.NEXT_PUBLIC_SLIDE_FONTS_V1 !== "0";
  } catch {
    return true;
  }
}

const GENERICS = new Set(["serif", "sans-serif", "monospace", "cursive", "fantasy", "system-ui", "ui-serif", "ui-sans-serif", "ui-monospace", "ui-rounded", "math", "emoji", "fangsong"]);
const LEGACY_SERIFS = new Set(["garamond", "palatino", "baskerville", "times"]);

const unquote = (s: string) => s.trim().replace(/^['"]|['"]$/g, "").trim();

/** First family of a CSS stack, unquoted. */
export function firstFamily(stored: string): string {
  return unquote(stored.split(",")[0] ?? "");
}

const byExact = new Map<string, FontEntry>();
const byLower = new Map<string, FontEntry>();
for (const e of FONT_REGISTRY) {
  byExact.set(e.family, e);
  byLower.set(e.family.toLowerCase(), e);
}
for (const e of FONT_REGISTRY) for (const a of e.aliases ?? []) if (!byLower.has(a.toLowerCase())) byLower.set(a.toLowerCase(), e);

/** exact → case-insensitive → alias → first family of a CSS stack. Unknown → undefined. */
export function resolveFont(stored: string | null | undefined): FontEntry | undefined {
  if (typeof stored !== "string") return undefined;
  const raw = stored.trim();
  if (!raw) return undefined;
  const hit = byExact.get(raw) ?? byLower.get(unquote(raw).toLowerCase());
  if (hit) return hit;
  if (raw.includes(",")) {
    const first = firstFamily(raw);
    return byExact.get(first) ?? byLower.get(first.toLowerCase());
  }
  return undefined;
}

// Multi-word names made of plain identifiers are valid unquoted CSS (and match the
// pre-registry wire strings byte-for-byte, e.g. "Times New Roman, serif").
const quoteFamily = (f: string) => (/^[a-zA-Z][a-zA-Z -]*$/.test(f) ? f : `"${f.replace(/"/g, "")}"`);

/**
 * Render-time CSS font-family that ALWAYS ends in a generic family, so a font
 * that is missing (Windows Helvetica, a failed download) degrades to the right
 * CLASS of face instead of the browser default serif (the 2026-08-11 "medieval
 * font" bug). Known fonts get their registry stack; unknown values keep their
 * raw text and gain a generic. Returns the raw value unchanged when the kill
 * switch is off. Never used to rewrite stored data.
 */
export function fontStack(stored: string | null | undefined): string | undefined {
  if (typeof stored !== "string") return undefined;
  const raw = stored.trim();
  if (!raw) return undefined;
  if (!slideFontsV1Enabled()) return stored;
  const parts = raw.split(",").map((p) => unquote(p)).filter(Boolean);
  const last = parts[parts.length - 1]?.toLowerCase() ?? "";
  if (parts.length > 1 && GENERICS.has(last)) return raw; // already a complete stack
  const entry = resolveFont(raw);
  if (entry && parts.length === 1) {
    return [entry.family, ...(entry.fallbacks ?? []), entry.generic].map((f) => (GENERICS.has(f) ? f : quoteFamily(f))).join(", ");
  }
  if (parts.length === 1 && GENERICS.has(last)) return raw; // bare generic ("serif")
  const generic: GenericFamily = entry?.generic ?? (LEGACY_SERIFS.has(firstFamily(raw).toLowerCase()) ? "serif" : "sans-serif");
  return `${raw}, ${generic}`;
}

export type FontPickerOption = { value: string; label: string; entry: FontEntry };

/** The one list every font picker renders (same order everywhere). */
export const FONT_PICKER_OPTIONS: readonly FontPickerOption[] = FONT_REGISTRY.map((e) => ({ value: e.family, label: e.label, entry: e }));

/**
 * Options for a <select> given the currently stored value. If the stored value
 * is not an option (unknown font, or a different spelling/stack), it is
 * prepended as "(current) <value>" so the picker shows the truth and never
 * silently overwrites it.
 */
export function pickerOptionsFor(current: string | null | undefined): { value: string; label: string }[] {
  const base = FONT_PICKER_OPTIONS.map((o) => ({ value: o.value, label: o.label }));
  if (typeof current !== "string" || !current || base.some((o) => o.value === current)) return base;
  return [{ value: current, label: `(current) ${current}` }, ...base];
}

/** The nearest real weight a font has (ties go to the heavier weight). Unknown font → requested weight. */
export function nearestWeight(stored: string | null | undefined, weight: number): number {
  const entry = resolveFont(stored);
  if (!entry || !entry.weights.length || !Number.isFinite(weight)) return weight;
  let best = entry.weights[0];
  for (const w of entry.weights) {
    if (Math.abs(w - weight) < Math.abs(best - weight) || (Math.abs(w - weight) === Math.abs(best - weight) && w > best)) best = w;
  }
  return best;
}

/** Weight options for a picker: the font's real weights, plus the stored weight if it isn't one. */
export function weightOptionsFor(stored: string | null | undefined, currentWeight?: number, fallback: number[] = [300, 400, 500, 600, 700, 800, 900]): number[] {
  const entry = resolveFont(stored);
  const list = entry ? [...entry.weights] : [...fallback];
  if (typeof currentWeight === "number" && Number.isFinite(currentWeight) && !list.includes(currentWeight)) list.push(currentWeight);
  return list.sort((a, b) => a - b);
}

/** A CSS font shorthand for document.fonts.load/check. */
export function fontLoadSpec(family: string, weight: number | string | undefined, italic: boolean, px = 48): string {
  const w = weight === undefined || weight === "" ? 400 : weight;
  return `${italic ? "italic " : ""}${w} ${px}px ${quoteFamily(firstFamily(family)) }`;
}
